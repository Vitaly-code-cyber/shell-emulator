"""Иерархия исключений эмулятора.

Все ошибки, о которых эмулятор сообщает пользователю, наследуются от
:class:`EmulatorError`. Это позволяет обрабатывать их единообразно:
в интерактивном режиме сообщение печатается и диалог продолжается,
а при выполнении стартового скрипта работа останавливается.
"""


class EmulatorError(Exception):
    """Базовая ошибка эмулятора, предназначенная для пользователя."""


class UnknownCommandError(EmulatorError):
    """Введена команда, отсутствующая в реестре команд."""


class CommandArgumentError(EmulatorError):
    """Команда вызвана с неверным числом или форматом аргументов."""
