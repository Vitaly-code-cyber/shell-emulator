#!/usr/bin/env bash
# Общие определения для скриптов тестирования эмулятора.
# Файл предназначен для подключения через source, а не для запуска.

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
EMU="$ROOT/run.sh"
BUILD_DIR="$ROOT/build"

mkdir -p "$BUILD_DIR"

# Печатает заголовок очередного шага тестирования.
step() {
    echo
    echo "--------------------------------------------------"
    echo "ШАГ: $1"
    echo "--------------------------------------------------"
}

# Запускает эмулятор с переданными параметрами и печатает код возврата.
run_emulator() {
    "$EMU" "$@" </dev/null
    echo "[код возврата: $?]"
}

# Собирает стартовый скрипт из стандартного ввода и запускает на нём
# эмулятор. Первый аргумент — имя создаваемого скрипта, остальные
# передаются эмулятору без изменений.
run_emulator_script() {
    local name="$1"
    shift
    local script="$BUILD_DIR/$name.vsh"
    cat > "$script"
    "$EMU" "$@" --script "$script" </dev/null
    echo "[код возврата: $?]"
}
